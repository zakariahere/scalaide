package dev.scalaide.workbench;

import com.intellij.openapi.Disposable;
import com.intellij.openapi.application.ApplicationManager;
import com.intellij.openapi.fileEditor.*;
import com.intellij.openapi.ide.CopyPasteManager;
import com.intellij.openapi.project.Project;
import com.intellij.ui.components.*;
import com.intellij.util.ui.JBUI;
import org.jetbrains.annotations.NotNull;
import javax.swing.*;
import java.awt.*;
import java.awt.datatransfer.StringSelection;
import java.time.LocalTime;
import java.time.format.DateTimeFormatter;
import java.util.concurrent.*;

/** Independent learning surface: only an explicit button/action submits a file. */
final class LearningPanel extends JPanel implements Disposable {
    private final Project project;
    private final JBLabel active = new JBLabel("Open a Scala file to begin.");
    private final JBTextArea status = text("Your learning summary will appear here.");
    private final JEditorPane summary = new JEditorPane();
    private final JButton summarize = new JButton("Summarize this Scala file");
    private final JButton cancel = new JButton("Cancel");
    private final JButton copy = new JButton("Copy learning notes");
    private final DeepSeekClient client = new DeepSeekClient();
    private final Object lock = new Object();
    private long generation;
    private CompletableFuture<DeepSeekClient.Summary> running;
    private Future<?> loadingKey;
    private volatile boolean disposed;
    private String notes = "";

    LearningPanel(Project project) {
        super(new BorderLayout(0, JBUI.scale(12)));
        this.project = project;
        setBorder(JBUI.Borders.empty(14));
        status.setFont(BrandIdentity.body(13)); status.setForeground(BrandIdentity.SECONDARY);
        var header = new JPanel(); header.setLayout(new BoxLayout(header, BoxLayout.Y_AXIS));
        var title = new JBLabel("Learn from your Scala"); title.setFont(BrandIdentity.display(22)); title.setForeground(BrandIdentity.ACCENT);
        header.add(title); header.add(Box.createVerticalStrut(JBUI.scale(8))); header.add(active);
        header.add(Box.createVerticalStrut(JBUI.scale(10)));
        var disclosure = text("Clicking Summarize sends the entire active Scala file, including comments and unsaved edits, to DeepSeek. No other project files are included.");
        disclosure.setFont(BrandIdentity.body(12)); disclosure.setForeground(BrandIdentity.MUTED); header.add(disclosure);
        header.add(Box.createVerticalStrut(JBUI.scale(10)));
        var controls = new JPanel(new BorderLayout(JBUI.scale(8), 0));
        controls.add(summarize, BorderLayout.CENTER); controls.add(cancel, BorderLayout.EAST); header.add(controls);
        header.add(Box.createVerticalStrut(JBUI.scale(8))); header.add(status);
        for (Component component : header.getComponents())
            if (component instanceof JComponent child) child.setAlignmentX(Component.LEFT_ALIGNMENT);
        add(header, BorderLayout.NORTH);
        summary.setEditable(false); summary.setContentType("text/html");
        summary.putClientProperty(JEditorPane.HONOR_DISPLAY_PROPERTIES, true);
        summary.setFont(BrandIdentity.body(14));
        summary.getAccessibleContext().setAccessibleName("Scala learning summary");
        add(new JBScrollPane(summary), BorderLayout.CENTER);
        var footer = new JPanel(new GridLayout(1, 2, JBUI.scale(8), 0));
        var settings = new JButton("Learning settings…"); footer.add(copy); footer.add(settings); add(footer, BorderLayout.SOUTH);
        cancel.setEnabled(false); copy.setEnabled(false);
        summarize.addActionListener(e -> summarizeCurrent());
        cancel.addActionListener(e -> cancel());
        settings.addActionListener(e -> new LearningSettingsDialog(project).show());
        copy.addActionListener(e -> CopyPasteManager.getInstance().setContents(new StringSelection(notes)));
        project.getMessageBus().connect(this).subscribe(FileEditorManagerListener.FILE_EDITOR_MANAGER, new FileEditorManagerListener() {
            @Override public void selectionChanged(@NotNull FileEditorManagerEvent event) { refreshActive(); }
        });
        refreshActive();
        render("## A little reflection after coding\nOpen a Scala file, then summarize it to review its concepts, useful Java comparisons, and a small practice exercise.\n\nAdd your DeepSeek key in Learning settings. Summaries are generated by AI from the file snapshot, not a record of what you have mastered.");
    }

    private static JBTextArea text(String value) {
        var area = new JBTextArea(value); area.setEditable(false); area.setOpaque(false);
        area.setLineWrap(true); area.setWrapStyleWord(true); return area;
    }
    private void refreshActive() {
        if (disposed) return;
        var files = FileEditorManager.getInstance(project).getSelectedFiles();
        String name = files.length > 0 ? files[0].getName() : "No file selected";
        active.setText(name); active.setToolTipText(name);
        synchronized (lock) {
            summarize.setEnabled(!cancel.isEnabled() && files.length > 0 && "Scala".equals(files[0].getFileType().getName())
                    && "scala".equals(files[0].getExtension()));
        }
    }

    void summarizeCurrent() {
        if (disposed || cancel.isEnabled()) return;
        final LearningSnapshot snapshot;
        try { snapshot = LearningSnapshot.capture(project); }
        catch (IllegalArgumentException problem) { status.setText(problem.getMessage()); return; }
        var preferences = LearningSettings.get().getState();
        String model = preferences.model, language = preferences.language;
        boolean compareJava = preferences.compareJava;
        String time = LocalTime.now().format(DateTimeFormatter.ofPattern("HH:mm:ss"));
        final long id;
        synchronized (lock) { id = ++generation; }
        cancel.setEnabled(true); summarize.setEnabled(false); copy.setEnabled(false); notes = "";
        render("## Preparing your learning summary\nDeepSeek will explain the concepts in this file snapshot.");
        status.setText("Summarizing " + snapshot.fileName() + " · " + time + " snapshot…");
        loadingKey = ApplicationManager.getApplication().executeOnPooledThread(() -> {
            try {
                String key = DeepSeekCredentials.load();
                if (key == null || key.isBlank()) throw new DeepSeekClient.LearningFailure("Add your DeepSeek API key in Learning settings, then click Summarize again.");
                CompletableFuture<DeepSeekClient.Summary> request;
                synchronized (lock) {
                    if (disposed || id != generation) return;
                    try { request = client.summarize(snapshot.fileName(), snapshot.source(), language, compareJava, model, key); }
                    catch (IllegalArgumentException invalid) { throw new DeepSeekClient.LearningFailure("Check the model, language and API key in Learning settings."); }
                    running = request;
                }
                request.whenComplete((answer, error) -> finish(id, snapshot, time, answer, error));
            } catch (Exception error) { finish(id, snapshot, time, null, error); }
        });
    }

    private void finish(long id, LearningSnapshot snapshot, String time, DeepSeekClient.Summary answer, Throwable error) {
        ApplicationManager.getApplication().invokeLater(() -> {
            synchronized (lock) {
                if (disposed || project.isDisposed() || id != generation) return;
                running = null;
            }
            cancel.setEnabled(false); refreshActive();
            if (error != null) {
                status.setText(DeepSeekClient.safeError(error));
                render("## Summary unavailable\nYour source was not modified. Review the status above, then try again when ready.");
                return;
            }
            String label = snapshot.fileName() + " · " + time + " snapshot";
            status.setText(label + (snapshot.changed() ? " · File changed during this request; summarize again for the latest version." : " · AI explanation; check it against your code.")
                    + (answer.truncated() ? " Output limit reached; this summary is partial." : ""));
            notes = "# Learning notes — " + label + "\n\n" + answer.markdown();
            render(answer.markdown()); copy.setEnabled(true);
        });
    }

    private void render(String markdown) {
        String foreground = hex(BrandIdentity.TEXT), background = hex(getBackground()), accent = hex(BrandIdentity.ACCENT);
        summary.setText("<html><head><style>body{font-family:sans-serif;font-size:13pt;color:" + foreground
                + ";background:" + background + ";margin:10px;} h2{font-size:16pt;color:" + accent
                + ";margin-top:18px;} p,li{margin-bottom:8px;} pre{font-family:monospace;font-size:11pt;} code{font-family:monospace;}</style></head><body>"
                + LearningMarkdown.body(markdown) + "</body></html>");
        summary.setCaretPosition(0);
    }
    private static String hex(Color color) { return String.format("#%02x%02x%02x", color.getRed(), color.getGreen(), color.getBlue()); }
    private void cancel() {
        synchronized (lock) { ++generation; if (running != null) running.cancel(true); running = null; }
        if (loadingKey != null) loadingKey.cancel(true);
        cancel.setEnabled(false); copy.setEnabled(false); refreshActive();
        status.setText("Summary cancelled. DeepSeek may still account for work already processed.");
        render("## Summary cancelled\nClick Summarize when you want to try again.");
    }
    @Override public void dispose() {
        disposed = true;
        synchronized (lock) { ++generation; if (running != null) running.cancel(true); running = null; }
        if (loadingKey != null) loadingKey.cancel(true);
        client.shutdown();
    }
}
